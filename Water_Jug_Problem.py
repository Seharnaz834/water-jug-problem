"""
Water Jug Problem - State Space Search (BFS & DFS)
Pynexia Technology - Internship Hands-On Project
Author: Sehar Naz

Problem: Jug X = 4 litres, Jug Y = 3 litres, Target = 2 litres
State: (x, y) = amount of water in Jug X and Jug Y
Initial state: (0, 0) | Goal test: x == 2 or y == 2
"""
from collections import deque
import math

CAP_X, CAP_Y, TARGET = 4, 3, 2


def successors(state):
    x, y = state
    moves = []
    # 1. Fill Jug X
    if x < CAP_X:
        moves.append(((CAP_X, y), "Fill Jug X (4L)"))
    # 2. Fill Jug Y
    if y < CAP_Y:
        moves.append(((x, CAP_Y), "Fill Jug Y (3L)"))
    # 3. Empty Jug X
    if x > 0:
        moves.append(((0, y), "Empty Jug X"))
    # 4. Empty Jug Y
    if y > 0:
        moves.append(((x, 0), "Empty Jug Y"))
    # 5. Pour X -> Y
    if x > 0 and y < CAP_Y:
        pour = min(x, CAP_Y - y)
        moves.append(((x - pour, y + pour), f"Pour Jug X -> Jug Y ({pour}L)"))
    # 6. Pour Y -> X
    if y > 0 and x < CAP_X:
        pour = min(y, CAP_X - x)
        moves.append(((x + pour, y - pour), f"Pour Jug Y -> Jug X ({pour}L)"))
    return moves


def is_goal(state):
    return state[0] == TARGET or state[1] == TARGET


def bfs(start=(0, 0)):
    queue = deque([start])
    visited = {start}
    parent = {start: (None, "Start - both jugs empty")}
    order = []
    while queue:
        state = queue.popleft()
        order.append(state)
        if is_goal(state):
            return reconstruct(parent, state), order, visited
        for nxt, action in successors(state):
            if nxt not in visited:
                visited.add(nxt)
                parent[nxt] = (state, action)
                queue.append(nxt)
    return None, order, visited


def dfs(start=(0, 0)):
    stack = [start]
    visited = {start}
    parent = {start: (None, "Start - both jugs empty")}
    order = []
    while stack:
        state = stack.pop()
        order.append(state)
        if is_goal(state):
            return reconstruct(parent, state), order, visited
        for nxt, action in reversed(successors(state)):
            if nxt not in visited:
                visited.add(nxt)
                parent[nxt] = (state, action)
                stack.append(nxt)
    return None, order, visited


def reconstruct(parent, goal):
    path = []
    cur = goal
    while cur is not None:
        prev, action = parent[cur]
        path.append((cur, action))
        cur = prev
    return list(reversed(path))


def validate(path, name):
    """Assert that a returned path is a genuine solution:
    it starts at (0, 0), every step follows one legal move
    generated by successors(), and the last state is a goal."""
    assert path, f"{name}: empty path"
    assert path[0][0] == (0, 0), f"{name}: path must start at (0, 0)"
    for (state, _), (nxt, action) in zip(path, path[1:]):
        legal = dict(successors(state))
        assert nxt in legal, f"{name}: illegal move {state} -> {nxt}"
        assert legal[nxt] == action, f"{name}: wrong label for {nxt}"
    assert is_goal(path[-1][0]), f"{name}: last state is not a goal"
    return True


def show(name, result):
    path, order, visited = result
    print(f"\n{'=' * 64}\n{name} SOLUTION\n{'=' * 64}")
    print(f"States explored (in order): {order}")
    print(f"Total distinct states visited: {len(visited)}")
    if not path:
        print("No solution found.")
        return
    print(f"Solution length: {len(path) - 1} steps\n")
    for i, (state, action) in enumerate(path):
        print(f"Step {i}: {state}  -  {action}")
    print(f"\nGoal reached: {path[-1][0]}  ->  {TARGET} litres measured successfully.")
    validate(path, name)
    print(f"Validation: PASSED - every transition is a legal move.")


if __name__ == "__main__":
    print("WATER JUG PROBLEM")
    print(f"Jug X capacity: {CAP_X}L | Jug Y capacity: {CAP_Y}L | Target: {TARGET}L")
    g = math.gcd(CAP_X, CAP_Y)
    print(f"Solvability check: gcd({CAP_X},{CAP_Y}) = {g} ;")
    print(f"{TARGET} is a multiple of {g} -> SOLVABLE")
    show("BREADTH-FIRST SEARCH (BFS)", bfs())
    show("DEPTH-FIRST SEARCH (DFS)", dfs())
